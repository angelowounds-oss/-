// Turns the OpenStreetMap place nodes (build/korea_places_fetch.py) into the list of every city and town of South Korea, in map metres
// (KOREA-PLAN C). Keeps points on land, drops a second node of the same name within 2 km, and writes src/koreaplaces.js (generated).
// Data: © OpenStreetMap contributors, ODbL 1.0 (docs/ASSETS.md).
// Usage: node build/korea_places_convert.mjs <korea_places_osm.json> <out.js>
import fs from 'node:fs';
import { project, koreaMask, landAt } from '../src/koreamap.js';

const [src, out] = process.argv.slice(2);
if (!src || !out) { console.error('usage: node build/korea_places_convert.mjs <korea_places_osm.json> <out.js>'); process.exit(2); }

const mask = koreaMask();
const nodes = JSON.parse(fs.readFileSync(src, 'utf8'));
const places = [], seen = [];
let offLand = 0, dup = 0;
for (const n of nodes) {
  if (!n.name) continue;
  const p = project(n.lon, n.lat);
  if (!landAt(mask, p.x, p.z)) { offLand++; continue; }
  if (seen.some((s) => s.name === n.name && Math.hypot(s.x - p.x, s.z - p.z) < 2000)) { dup++; continue; }
  const pop = n.population ? parseInt(n.population, 10) : null;
  const rec = { n: n.name, k: n.place === 'city' ? 'city' : 'town', p: Number.isFinite(pop) ? pop : null, x: Math.round(p.x), z: Math.round(p.z) };
  seen.push(rec); places.push(rec);
}
places.sort((a, b) => (b.p || 0) - (a.p || 0));
fs.writeFileSync(out, '// Generated by build/korea_places_convert.mjs from OpenStreetMap place nodes (ODbL, credited in game). Do not edit by hand.\n' +
  'export const PLACES = ' + JSON.stringify(places) + ';\n');
console.log(`${places.length} places (${places.filter((q) => q.k === 'city').length} cities), ${offLand} off land, ${dup} duplicates`);
