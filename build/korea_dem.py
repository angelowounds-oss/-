# Elevation grid for the Korea map (WLD-20e): samples the public Terrarium terrain tiles (SRTM-based, AWS Open Data) at the
# height-grid nodes of src/worldmap.js (257 x 257 nodes, 390 m apart, map frame) and writes assets/korea/dem.bin (int16, row-major
# j*N1+i, x = -50000 + i*CC, z = -50000 + j*CC) and src/koreadem.js (the same bytes, base64, like korealand.js).
# Run: python3 build/korea_dem.py   (needs Pillow and network; the tiles are cached in build/.dem-tiles, not committed)
import base64, concurrent.futures as cf, math, os, struct, urllib.request
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
TILES = os.path.join(os.path.dirname(os.path.abspath(__file__)), '.dem-tiles')
SCALE, LON0, LAT0, HALF, CG, Z = 6.5, 127.77, 35.9, 50000, 256, 10
R = 6371000 / SCALE
CC = 2 * HALF / CG; N1 = CG + 1; N = 2 ** Z * 256
# the world square in map metres is -HALF..HALF; these tiles cover its lon/lat box (124.0-131.5 E, 32.9-38.8 N)
XS, YS = range(864, 887), range(391, 413)

def inv(x, z):   # map metres -> lon/lat (inverse of the azimuthal equidistant projection in src/koreamap.js)
    X, Y = x, -z; rho = math.hypot(X, Y)
    if rho < 1e-9: return LON0, LAT0
    c = rho / R; p0 = math.radians(LAT0)
    lat = math.asin(math.cos(c) * math.sin(p0) + Y * math.sin(c) * math.cos(p0) / rho)
    lon = math.radians(LON0) + math.atan2(X * math.sin(c), rho * math.cos(p0) * math.cos(c) - Y * math.sin(p0) * math.sin(c))
    return math.degrees(lon), math.degrees(lat)

def fetch():
    os.makedirs(TILES, exist_ok=True)
    jobs = [(x, y) for x in XS for y in YS]
    def get(job):
        x, y = job; p = os.path.join(TILES, f'{x}_{y}.png')
        if os.path.exists(p) and os.path.getsize(p) > 0: return
        url = f'https://elevation-tiles-prod.s3.amazonaws.com/terrarium/{Z}/{x}/{y}.png'
        with urllib.request.urlopen(url, timeout=60) as r, open(p, 'wb') as f: f.write(r.read())
    with cf.ThreadPoolExecutor(12) as ex: list(ex.map(get, jobs))

_cache = {}
def elev(lon, lat):
    px = (lon + 180) / 360 * N; r = math.radians(lat)
    py = (1 - math.log(math.tan(r) + 1 / math.cos(r)) / math.pi) / 2 * N
    k = (int(px // 256), int(py // 256))
    if k not in _cache: _cache[k] = Image.open(os.path.join(TILES, f'{k[0]}_{k[1]}.png')).convert('RGB').load()
    p = _cache[k][int(px) % 256, int(py) % 256]
    return p[0] * 256 + p[1] + p[2] / 256 - 32768   # Terrarium encoding

def main():
    fetch()
    H = []
    for j in range(N1):
        for i in range(N1):
            lon, lat = inv(-HALF + i * CC, -HALF + j * CC)
            H.append(int(round(elev(lon, lat))))
    data = struct.pack(f'<{len(H)}h', *H)
    os.makedirs(os.path.join(ROOT, 'assets/korea'), exist_ok=True)
    with open(os.path.join(ROOT, 'assets/korea/dem.bin'), 'wb') as f: f.write(data)
    b64 = base64.b64encode(data).decode()
    with open(os.path.join(ROOT, 'src/koreadem.js'), 'w') as f:
        f.write('// Generated by build/korea_dem.py from the public Terrarium terrain tiles. Do not edit by hand.\n')
        f.write(f'export const DEM_N1 = {N1};\nexport const DEM_B64 = "{b64}";\n')
    print('nodes', len(H), 'min', min(H), 'max', max(H))

if __name__ == '__main__':
    main()
